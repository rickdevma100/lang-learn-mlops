# Singleton text pool instance
_text_pool: TextPool | None = None


def _get_text_pool() -> TextPool:
    global _text_pool
    if _text_pool is None:
        _text_pool = TextPool()
        stats = _text_pool.seed_pool()
        logger.info("Text pool initialized: %s", stats)
    return _text_pool


# Schreiben ring buffers for anti-repeat fallback
_recent_pool_history: Dict[str, collections.deque] = {
    "schreiben_t1": collections.deque(maxlen=4),
    "schreiben_t2": collections.deque(maxlen=4),
}


def _pick_distinct_pool_item(pool: List[Dict[str, Any]], key: str) -> Dict[str, Any]:
    history = _recent_pool_history.setdefault(key, collections.deque(maxlen=max(1, len(pool) - 1)))
    available_indices = [i for i in range(len(pool)) if i not in history]
    if not available_indices:
        history.clear()
        available_indices = list(range(len(pool)))
    choice_idx = random.choice(available_indices)
    history.append(choice_idx)
    return pool[choice_idx]


# ---------------------------------------------------------------------------
# JSON parsing & normalization helpers
# ---------------------------------------------------------------------------

def _repair_json_string(text: str) -> str:
    """Repair common JSON formatting errors from LLMs."""
    text = re.sub(r':\s*(?!")([A-ZÄÖÜa-zäöüß][^",}\]]*?")', r': "\1', text)
    text = re.sub(r',\s*([\}\]])', r'\1', text)
    return text


def _try_parse_json(text: str) -> Any | None:
    try:
        return json.loads(text)
    except (json.JSONDecodeError, ValueError):
        return None


def _extract_json(text: str) -> Any | None:
    """Robustly extract and parse JSON from LLM output."""
    if not text or not text.strip():
        return None

    cleaned = text.strip()
    cleaned = re.sub(r"^```(?:json|JSON)?\s*\n?", "", cleaned)
    cleaned = re.sub(r"\n?\s*```\s*$", "", cleaned)
    cleaned = cleaned.strip()

    result = _try_parse_json(cleaned)
    if result is not None:
        return result

    repaired = _repair_json_string(cleaned)
    result = _try_parse_json(repaired)
    if result is not None:
        return result

    arr_match = re.search(r"(\[.*\])", repaired, re.DOTALL)
    if arr_match:
        result = _try_parse_json(arr_match.group(1))
        if result is not None:
            return result

    obj_match = re.search(r"(\{.*\})", repaired, re.DOTALL)
    if obj_match:
        result = _try_parse_json(obj_match.group(1))
        if result is not None:
            return result

    for start_char in ("[", "{"):
        start_idx = repaired.find(start_char)
        if start_idx == -1:
            continue
        truncated = repaired[start_idx:]
        lines = truncated.split('\n')
        for trim_count in range(min(len(lines), 12)):
            candidate_lines = lines[:len(lines) - trim_count] if trim_count > 0 else lines
            candidate = '\n'.join(candidate_lines)
            candidate = re.sub(r',\s*$', '', candidate.rstrip())
            open_braces = candidate.count('{') - candidate.count('}')
            open_brackets = candidate.count('[') - candidate.count(']')
            suffix = ']' * max(0, open_brackets) + '}' * max(0, open_braces)
            if suffix or trim_count > 0:
                attempt = candidate + suffix
                result = _try_parse_json(attempt)
                if result is not None:
                    return result
                attempt_repaired = _repair_json_string(attempt)
                result = _try_parse_json(attempt_repaired)
                if result is not None:
                    return result

    logger.warning("All JSON extraction attempts failed on LLM output length: %d", len(text))
    return None


def _normalize_option_letter(val: Any, valid_set: tuple = ("a", "b", "c")) -> str:
    if val is None:
        return valid_set[0]
    s = str(val).strip().lower()
    if s in valid_set:
        return s
    if "x" in valid_set and any(k in s for k in ("kein", "nein", "none", "nicht", "x")):
        return "x"
    m = re.search(r"\b([a-z])\b", s)
    if m and m.group(1) in valid_set:
        return m.group(1)
    if s and s[0] in valid_set:
        return s[0]
    return valid_set[0]


def _extract_item_answer(item: Dict[str, Any], default: str = "a", valid_options: tuple = ("a", "b", "c")) -> str:
    raw = (
        item.get("answer_key")
        or item.get("answer")
        or item.get("correct_answer")
        or item.get("solution")
        or item.get("correct_option")
        or item.get("correct")
        or default
    )
    return _normalize_option_letter(raw, valid_set=valid_options)


def _normalize_options_dict(raw_opts: Any) -> Dict[str, str]:
    if isinstance(raw_opts, list):
        return {chr(ord('a') + i): str(opt) for i, opt in enumerate(raw_opts[:3])}
    elif isinstance(raw_opts, dict):
        normalized = {}
        for k, v in raw_opts.items():
            norm_key = _normalize_option_letter(k, valid_set=("a", "b", "c"))
            normalized[norm_key] = str(v)
        for k in ("a", "b", "c"):
            if k not in normalized:
                normalized[k] = f"Option {k.upper()}"
        return normalized
    return {"a": "Option A", "b": "Option B", "c": "Option C"}


def _sanitize_mcq_items(
    items_raw: List[Dict],
    id_start: int,
    count: int = 5,
    valid_options: tuple = ("a", "b", "c")
) -> Tuple[List[Dict], Dict, Dict]:
    sanitized_items = []
    answer_key = {}
    explanations = {}

    for idx, item in enumerate(items_raw[:count], start=id_start):
        q_id = idx
        ans = _extract_item_answer(item, default=valid_options[0], valid_options=valid_options)
        exp = str(item.get("explanation") or item.get("reason") or "Richtige Antwort laut Text.")

        if valid_options == ("a", "b", "c"):
            opts = _normalize_options_dict(item.get("options", {}))
            sanitized_items.append({
                "id": q_id,
                "question": str(item.get("question", "")),
                "options": opts
            })
        else:
            sanitized_items.append({
                "id": q_id,
                "question": str(item.get("question", ""))
            })

        answer_key[str(q_id)] = ans
        explanations[str(q_id)] = exp

    return sanitized_items, answer_key, explanations


# ---------------------------------------------------------------------------
# LLM Question Generation Functions (Called via External Metal LLM)
# ---------------------------------------------------------------------------

async def _generate_questions_for_text(
    text: str,
    teil_type: str,
    num_questions: int = 5,
    id_start: int = 1,
    max_retries: int = 2,
) -> List[Dict[str, Any]]:
    """Prompt the external LLM to generate multiple-choice questions for a given German text."""
    id_end = id_start + num_questions - 1
    prompt = (
        f"You are creating Goethe-Zertifikat A2 Reading comprehension questions.\n"
        f"Read this German {teil_type}:\n\n"
        f"{text}\n\n"
        f"Create exactly {num_questions} multiple-choice questions numbered {id_start} to {id_end} about the text above.\n"
        f"Each question must have 3 options ('a', 'b', 'c'), an 'answer_key' ('a', 'b', or 'c'), and a German 'explanation'.\n"
        f"Return ONLY a valid JSON array matching this structure:\n"
        f"[\n"
        f'  {{"id": {id_start}, "question": "Frage auf Deutsch?", "options": {{"a": "Option A", "b": "Option B", "c": "Option C"}}, "answer_key": "a", "explanation": "Erklärung laut Text."}}\n'
        f"]"
    )

    for attempt in range(1, max_retries + 1):
        try:
            raw = await asyncio.wait_for(
                asyncio.to_thread(generate_external, prompt, 800, 0.2),
                timeout=90.0
            )
            parsed = _extract_json(raw)
            items = None
            if isinstance(parsed, list):
                items = parsed
            elif isinstance(parsed, dict):
                items = parsed.get("items") or parsed.get("questions")

            if items and len(items) >= 1:
                logger.info("Generated %d questions on attempt %d for %s", len(items), attempt, teil_type)
                # Pad to num_questions if needed
                while len(items) < num_questions:
                    pad_id = id_start + len(items)
                    items.append({
                        "id": pad_id,
                        "question": f"Was wird im Text zu Punkt {pad_id} gesagt?",
                        "options": {"a": "Wichtige Information", "b": "Zusätzliches Detail", "c": "Keine Angabe"},
                        "answer_key": "a",
                        "explanation": "Laut Text ist diese Information korrekt."
                    })
                return items[:num_questions]
            else:
                logger.warning("Attempt %d for %s returned insufficient items (%d)", attempt, teil_type, len(items) if items else 0)
        except Exception as e:
            logger.warning("Attempt %d error generating questions for %s: %s", attempt, teil_type, e)

    # Fallback to prevent exam generation from crashing
    logger.warning("Using fallback questions for %s", teil_type)
    fallback_items = []
    for i in range(num_questions):
        q_id = id_start + i
        fallback_items.append({
            "id": q_id,
            "question": f"Was ist laut Text für Frage {q_id} richtig?",
            "options": {"a": "Aussage A aus dem Text", "b": "Aussage B", "c": "Aussage C"},
            "answer_key": "a",
            "explanation": "Erklärung laut dem bereitgestellten Text."
        })
    return fallback_items


