async def generate_lesen_teil4(level: str = "A2") -> Tuple[Dict[str, Any], Dict[str, Any]]:
    """Lesen Teil 4: Classified Ads from pool + LLM generated person-matching questions."""
    pool = _get_text_pool()
    text_data = pool.get_random_text("lesen_teil4")

    ads_text = ""
    for ad in text_data.get("ads", []):
        ads_text += f"Anzeige {ad['id'].upper()}: {ad['title']} - {ad['text']}\n\n"

    prompt = (
        f"Read these 6 classified ads:\n\n{ads_text}\n"
        "Generate 5 questions (IDs 16 to 20). Each question describes a person looking for something specific in German.\n"
        "The person must match EXACTLY ONE ad (answer_key 'a'-'f'), or NO ad (answer_key 'x').\n"
        "At least 3 questions must match an ad. At least 1 question must be 'x' (no match).\n"
        "Return ONLY a valid JSON array:\n"
        "[\n"
        '  {"id": 16, "question": "Personenbeschreibung auf Deutsch...", "answer_key": "b", "explanation": "Erklärung..."},\n'
        '  {"id": 17, "question": "Personenbeschreibung auf Deutsch...", "answer_key": "d", "explanation": "Erklärung..."},\n'
        '  {"id": 18, "question": "Personenbeschreibung auf Deutsch...", "answer_key": "a", "explanation": "Erklärung..."},\n'
        '  {"id": 19, "question": "Personenbeschreibung auf Deutsch...", "answer_key": "f", "explanation": "Erklärung..."},\n'
        '  {"id": 20, "question": "Personenbeschreibung auf Deutsch...", "answer_key": "x", "explanation": "Keine Anzeige passt."}\n'
        "]"
    )

    items_raw = None
    for attempt in range(1, 3):
        try:
            raw = await asyncio.wait_for(
                asyncio.to_thread(generate_external, prompt, 800, 0.2),
                timeout=90.0
            )
            parsed = _extract_json(raw)
            if isinstance(parsed, list) and len(parsed) >= 1:
                items_raw = parsed
                break
            elif isinstance(parsed, dict) and "items" in parsed:
                items_raw = parsed["items"]
                break
        except Exception as e:
            logger.warning("Teil 4 question generation attempt %d error: %s", attempt, e)

    if not items_raw:
        logger.warning("Using fallback for Lesen Teil 4")
        items_raw = [
            {"id": 16, "question": "Herr Becker sucht ein günstiges Fahrrad.", "answer_key": "a", "explanation": "Anzeige A bietet Fahrräder an."},
            {"id": 17, "question": "Frau Klein möchte am Wochenende wandern gehen.", "answer_key": "b", "explanation": "Anzeige B bietet Wanderungen an."},
            {"id": 18, "question": "Thomas sucht eine Wohnung in der Stadtmitte.", "answer_key": "c", "explanation": "Anzeige C bietet Wohnungen an."},
            {"id": 19, "question": "Sarah möchte Spanisch lernen.", "answer_key": "d", "explanation": "Anzeige D bietet Sprachkurse an."},
            {"id": 20, "question": "Familie Meyer sucht ein Segelboot für den Urlaub.", "answer_key": "x", "explanation": "Keine Anzeige passt zu Segelbooten."}
        ]

    valid_options = ("a", "b", "c", "d", "e", "f", "x")
    sanitized_items, answer_key, explanations = _sanitize_mcq_items(
        items_raw, id_start=16, valid_options=valid_options
    )

    sanitized = {
        "teil": 4,
        "title": text_data.get("title", "Lesen Teil 4: Anzeigen & Personen"),
        "ads": text_data["ads"],
        "items": sanitized_items,
        "source": "hybrid"
    }
    return sanitized, {"answer_key": answer_key, "explanations": explanations}


